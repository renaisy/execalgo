"""Perturbative coefficients for the power-law deformation f(x; eps) = x^{1-eps}.

The coefficients v_m solve A v_{m+1} - ell_{m+1} = -S_m under the share
constraint, where S_m is the order-m source. For this deformation the source
is assembled from two auxiliary series in eps, both generated by the standard
exp and log recursions:

    L(eps) = log v(eps),        so  m V_m = sum_{j=1}^{m} j L_j V_{m-j},
    E(eps) = v(eps)^{-eps},     so  m E_m = sum_{j=1}^{m} j W_j E_{m-j},

with W_j = -L_{j-1} the coefficients of -eps L(eps). Then

    f(v;eps)   = v * E(eps),
    f_x(v;eps) = (1 - eps) E(eps),

whose eps^{m+1} coefficients are sum_i V_i E_{m+1-i} and E_{m+1} - E_m. In
each case the term containing the unknown V_{m+1} is the linear part, which
sits on the left-hand side inside A, so the sums below stop one short.

Benchmark cross term. When the objective is slippage against a VWAP
benchmark rather than against the arrival price, the controllable cost
acquires the extra term

    - int f(v(s)) q(s) ds,      q = (X/M) Q mu,

where mu is the market trading rate and M = int mu (see vwap.py). Its
contribution to the gradient is -f_x(v) q, which has no V_{m+1} part and so
enters only the sources: the baseline right-hand side becomes q and every
order gains -(E_{m+1} - E_m) q. Passing q = 0 reproduces the arrival-price
(IS) expansion exactly.

Adapted from gordonritter/perturbative-impact (MIT license).
"""

import numpy as np


def coefficients(grid, solver, share, max_order, cross=None, offset=None):
    """Return [v_0, ..., v_{max_order}] on the grid.

    `cross` is the VWAP benchmark vector q; None means the arrival-price
    (IS) objective. `offset` is an eps-independent constant right-hand-side
    vector (the inventory-risk term's 2*risk*share*(T - t)); it enters the
    baseline only — higher-order sources are unaffected because it carries
    no eps dependence.
    """
    if cross is None:
        cross = np.zeros(grid.size)
    if offset is None:
        offset = np.zeros(grid.size)
    baseline, _ = solver.solve(cross + offset, share)
    if baseline.min() <= 0.0:
        raise ValueError(
            "linear baseline has non-positive entries: the asymptotic expansion "
            "needs log(v) (benchmark-gaming / strong-risk regime). Use "
            "solve(method='continuation'), which enforces the long-only box "
            "structurally via the active-set solver."
        )
    rates = [baseline]
    future_images = [grid.future @ baseline]
    log_series = [np.log(baseline)]
    inverse_power = [np.ones(grid.size)]

    for order in range(max_order):
        if order >= 1:
            convolved = sum(
                j * log_series[j] * rates[order - j] for j in range(1, order)
            )
            log_series.append((rates[order] - convolved / order) / rates[0])

        next_order = order + 1
        inverse_power.append(
            sum(
                j * (-log_series[j - 1]) * inverse_power[next_order - j]
                for j in range(1, next_order + 1)
            )
            / next_order
        )

        impact_series = sum(
            rates[i] * inverse_power[next_order - i] for i in range(next_order)
        )
        slope_series = sum(
            (inverse_power[j] - inverse_power[j - 1]) * future_images[next_order - j]
            for j in range(1, next_order + 1)
        )
        slope_difference = inverse_power[next_order] - inverse_power[next_order - 1]
        source = grid.past @ impact_series + slope_series - slope_difference * cross

        correction, _ = solver.solve(-source, 0.0)
        rates.append(correction)
        future_images.append(grid.future @ correction)

    return rates


def partial_sum(series, eps, order):
    """The truncation v^{[order]} = sum_{m <= order} eps^m v_m."""
    return sum(eps**m * series[m] for m in range(order + 1))


def optimal_truncation_order(grid, series, eps):
    """The asymptotically optimal truncation order for the series at `eps`.

    Truncating a divergent asymptotic series where its terms are smallest
    requires no reference solution: the error left is of the order of the
    first discarded term, so the optimum is the m minimizing ||eps^m v_m||.
    """
    norms = [eps**m * grid.norm(series[m]) for m in range(len(series))]
    return int(np.argmin(norms))
